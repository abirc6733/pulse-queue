package types

import (
	"time"
)

// Option configures task parameters.
type Option func(*Task)

// WithPriority sets the priority of the task.
func WithPriority(p Priority) Option {
	return func(t *Task) {
		t.Priority = p
	}
}

// WithMaxRetries sets the maximum number of retry attempts before sending to DLQ.
func WithMaxRetries(retries int) Option {
	return func(t *Task) {
		if retries >= 0 {
			t.MaxRetries = retries
		}
	}
}

// WithTimeout sets the maximum execution duration allowed for this task.
func WithTimeout(d time.Duration) Option {
	return func(t *Task) {
		if d > 0 {
			t.Timeout = d
		}
	}
}

// WithDelay delays task execution by the given duration.
func WithDelay(d time.Duration) Option {
	return func(t *Task) {
		if d > 0 {
			t.ScheduledAt = time.Now().UTC().Add(d)
		}
	}
}

// WithSchedule schedules task execution at a specific UTC timestamp.
func WithSchedule(at time.Time) Option {
	return func(t *Task) {
		t.ScheduledAt = at.UTC()
	}
}

// WithUniqueKey enforces deduplication / idempotency within the given TTL.
func WithUniqueKey(key string, ttl time.Duration) Option {
	return func(t *Task) {
		t.UniqueKey = key
		t.UniqueTTL = ttl
	}
}

// WithID overrides the autogenerated UUID with a custom task ID.
func WithID(id string) Option {
	return func(t *Task) {
		if id != "" {
			t.ID = id
		}
	}
}
